"""Combine the key-personnel biosketches into one PDF for the Keck application.

Order: Prochaska (Lead PI), Edwards, Zhang. Sources are read from ~/Downloads and left
untouched; output is proposals/Keck_2027/BioSketches.pdf.

Run:
    conda run -n ocean14 python proposals/Keck_2027/scripts/merge_biosketches.py

Generated by JXP and Claude.
"""
from pathlib import Path
from pypdf import PdfReader, PdfWriter

DOWNLOADS = Path.home() / 'Downloads'
SOURCES = [
    ('Prochaska', DOWNLOADS / 'CV_Oceanography.pdf'),
    ('Edwards', DOWNLOADS / 'Edwards_cv_202610.pdf'),
    ('Zhang', DOWNLOADS / 'cv-yi zhang nih 2026 10.pdf'),
]
OUT = Path(__file__).resolve().parents[1] / 'BioSketches.pdf'


def main():
    writer = PdfWriter()
    for name, path in SOURCES:
        reader = PdfReader(path)
        start = len(writer.pages)
        for page in reader.pages:
            writer.add_page(page)
        writer.add_outline_item(name, start)  # bookmark per person
        print(f'{name:<10} {len(reader.pages)} pp  from {path.name}')
    writer.add_metadata({'/Title': 'Biographical Sketches: Prochaska, Edwards, Zhang'})
    with open(OUT, 'wb') as fh:
        writer.write(fh)
    print(f'wrote {OUT} ({len(writer.pages)} pp)')


if __name__ == '__main__':
    main()

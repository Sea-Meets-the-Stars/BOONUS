"""Check the Keck Project Summary fields in internal_proposal.md.

Parses every fenced block of the form

    ```keck:<field>
    text ...
    ```

in the proposal file, collapses line wraps to single spaces (the InfoReady and Keck
portals take one paragraph per field), and reports for each block: the character count
against Keck's limit (Application Instructions, 26 Aug 2026; limits include spaces),
whether the text is pure ASCII (the intake form is straight ASCII), and whether it still
holds a [bracketed placeholder]. Writes the paste-ready, unwrapped ASCII text of every
field to internal_proposal_fields.txt beside the proposal.

Run:
    conda run -n ocean14 python proposals/Keck_2027/scripts/count_chars.py
    conda run -n ocean14 python proposals/Keck_2027/scripts/count_chars.py path/to/other.md

Exit status 1 if any field is over its limit or non-ASCII.

Generated by JXP and Claude.
"""
import re
import sys
from pathlib import Path

# Keck limits. Fields that may repeat (impact: exactly 2; peer_group: 2 to 4) are
# written as scientific_question, potential_impact_1, potential_impact_2, peer_group_1 ...
LIMITS = {
    'title': 200,
    'scientific_question': 300,
    'potential_impact': 600,
    'risks': 300,
    'enabling_advances': 300,
    'new_area': 600,
    'peer_group': 300,
    'prior_support': 600,
    'ai_use': 300,
    'abstract': 1800,
    'graphical_abstract_caption': 300,
}
REQUIRED = ['scientific_question', 'potential_impact_1', 'potential_impact_2', 'risks',
            'enabling_advances', 'new_area', 'peer_group_1', 'peer_group_2',
            'prior_support', 'ai_use']

FENCE = re.compile(r'```keck:([a-z_0-9]+)\n(.*?)```', re.S)


def base_field(name):
    return re.sub(r'_\d+$', '', name)


def unwrap(text):
    paras = [' '.join(p.split()) for p in re.split(r'\n\s*\n', text.strip())]
    return ' '.join(p for p in paras if p)


def main(path):
    src = Path(path).read_text()
    blocks = FENCE.findall(src)
    if not blocks:
        print(f'no ```keck:<field> blocks found in {path}')
        return 1
    bad = 0
    out = []
    seen = []
    width = max(len(n) for n, _ in blocks)
    for name, raw in blocks:
        seen.append(name)
        text = unwrap(raw)
        limit = LIMITS.get(base_field(name))
        n = len(text)
        flags = []
        if limit is None:
            flags.append('UNKNOWN FIELD')
            bad += 1
        elif n > limit:
            flags.append(f'OVER by {n - limit}')
            bad += 1
        non_ascii = [(i, c) for i, c in enumerate(text) if ord(c) > 126 or (ord(c) < 32)]
        if non_ascii:
            i, c = non_ascii[0]
            flags.append(f'NON-ASCII U+{ord(c):04X} at {i} ({len(non_ascii)} total)')
            bad += 1
        if '[' in text:
            flags.append('PLACEHOLDER')
        status = 'OK  ' if not flags else 'FAIL' if any(f.startswith(('OVER', 'NON', 'UNK')) for f in flags) else 'WARN'
        print(f"{status} {name:<{width}}  {n:4d}/{limit if limit else '?':<4}  {'; '.join(flags)}")
        out.append(f'### {name} ({n}/{limit})\n{text}\n')
    missing = [r for r in REQUIRED if r not in seen]
    if missing:
        print('MISSING required fields:', ', '.join(missing))
        bad += 1
    peers = [s for s in seen if s.startswith('peer_group')]
    if not 2 <= len(peers) <= 4:
        print(f'peer_group count {len(peers)} outside 2-4')
        bad += 1
    dest = Path(path).with_name('internal_proposal_fields.txt')
    dest.write_text('\n'.join(out), encoding='ascii', errors='strict')
    print(f'paste-ready text written to {dest}')
    return 1 if bad else 0


if __name__ == '__main__':
    target = sys.argv[1] if len(sys.argv) > 1 else \
        Path(__file__).resolve().parents[1] / 'internal_proposal.md'
    sys.exit(main(target))

""" Draw Figure 2 of da_ai_review.md: 2018-2026 milestones of AI in data assimilation.

Two tracks, numerical weather prediction (NWP) and ocean, each carrying the exemplars
that Sections 6 and 7 of the report cite.  Every milestone in MILESTONES below is dated
from a reference in ../sources.bib and carries that reference's BibTeX key; the script
refuses to run if a key is missing from sources.bib or if the date disagrees with what
the BibTeX record supports.  Three dating bases are used, and each milestone states its
own:

  'arxiv'  the month of the first arXiv version, read from the YYMM prefix of the
           `eprint` field (the preprint date; the journal year may be later);
  'month'  the `month` and `year` fields of the record: for journal articles the
           Crossref online-publication month that build_bib.py records (since
           2026-09-24, DA60), for grey items the month stated by the source (the day,
           where given, comes from the sources.md annotation of the same record);
  'year'   the record carries a year only, so the milestone is plotted at mid-year
           (1 July) and drawn with a bar spanning the whole year to say so (no
           milestone uses this basis since 2026-09-24; the code path is kept).

Marker colour gives the track and marker shape the taxonomy category of the report
(1 emulators/surrogates, 2 ML inside classical DA, 3 ML replacing DA, 4 ML around DA).
Labels alternate between the two sides of their track and are placed by a greedy
routine that measures each rendered label, tries increasing levels away from the track
and a few anchorings at each level, and accepts the first position where no box or
leader line crosses another (see place_labels), so nothing is drawn on top of anything
else; two milestones with the same date on one track have their markers nudged 32 days
apart for drawing only.  Colours are from the Okabe-Ito colour-blind-safe set.

Output: ../figs/ai_da_timeline.png (200 dpi, white background).

Usage (from reports/data_assimilation/, ocean14):
    conda run -n ocean14 python scripts/make_timeline.py

History: written 2026-09-24 (prompt #7); 24 milestones (11 NWP, 13 ocean), 14 dated
by arXiv month, 1 by a month field, 9 by year only.  Revised 2026-09-24 (prompt #8,
DA60): the nine year-only milestones moved to the `month` basis from the Crossref
published-online month now in sources.bib (Bonavita 2020-11, Hatfield 2021-09,
Pangu-Weather 2023-07, GenCast 2024-12, Aardvark 2025-03, CANYON-B 2018-09, LDEO-HPD
2022-01, Martin 2023-05, WenHai 2025-03); 14 arXiv, 10 month, 0 year.

Generated by JXP and Claude
"""

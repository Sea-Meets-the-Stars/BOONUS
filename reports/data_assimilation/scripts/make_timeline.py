def parse_bib(path):
    """ Return {key: {field: value}} for every record in a BibTeX file.

    Generated by JXP and Claude """
    with open(path) as fh:
        text = fh.read()
    records = {}
    for m in re.finditer(r'^@(\w+)\{([^,\s]+),(.*?)^\}', text, flags=re.M | re.S):
        fields = {}
        for f in re.finditer(r'^\s*(\w+)\s*=\s*\{(.*?)\},?\s*$', m.group(3), flags=re.M):
            fields[f.group(1).lower()] = f.group(2)
        records[m.group(2)] = fields
    return records


def check_milestone(date, key, basis, rec):
    """ Raise if the milestone date is not supported by the BibTeX record.

    Generated by JXP and Claude """
    year = int(rec.get('year', '0'))
    if basis == 'year':
        if (date.year, date.month, date.day) != (year, 7, 1):
            raise ValueError(f"{key}: basis 'year' requires {year}-07-01, got {date}")
    elif basis == 'arxiv':
        eprint = rec.get('eprint', '')
        if not re.match(r'^\d{4}\.\d{4,5}$', eprint):
            raise ValueError(f"{key}: basis 'arxiv' but no new-style eprint field ({eprint!r})")
        yy, mm = int(eprint[:2]) + 2000, int(eprint[2:4])
        if (date.year, date.month) != (yy, mm):
            raise ValueError(f"{key}: eprint {eprint} gives {yy}-{mm:02d}, got {date}")
    elif basis == 'month':
        mon = rec.get('month', '').strip().lower()[:3]
        if mon not in MONTHS:
            raise ValueError(f"{key}: basis 'month' but month field is {rec.get('month')!r}")
        if (date.year, date.month) != (year, MONTHS[mon]):
            raise ValueError(f"{key}: record gives {year}-{MONTHS[mon]:02d}, got {date}")
    else:
        raise ValueError(f"{key}: unknown basis {basis!r}")


def load_milestones():
    """ Validate MILESTONES against sources.bib and return them with date objects.

    Generated by JXP and Claude """
    bib = parse_bib(BIB)
    out = []
    for date_s, track, cat, label, key, basis in MILESTONES:
        if key not in bib:
            sys.exit(f"ERROR: key {key!r} is not in {BIB}")
        if track not in TRACKS or cat not in CATEGORY_MARKERS:
            sys.exit(f"ERROR: bad track or category for {key}")
        date = dt.date.fromisoformat(date_s)
        try:
            check_milestone(date, key, basis, bib[key])
        except ValueError as err:
            sys.exit(f"ERROR: {err}")
        out.append(dict(date=date, track=track, cat=cat, label=label, key=key, basis=basis))
    out.sort(key=lambda m: m['date'])
    # two milestones on one track with the same date: nudge the second by 32 days so the
    # markers and leaders stay distinct (the date itself is unchanged in MILESTONES)
    for i, m in enumerate(out):
        x = m['date']
        taken = [o['x'] for o in out[:i] if o['track'] == m['track']]
        while x in taken:
            x = x + dt.timedelta(days=32)
        m['x'] = x
    # labels alternate between the two sides of each track, in date order, so that each
    # side carries every other milestone (outer side first: above NWP, below ocean)
    count = {t: 0 for t in TRACKS}
    for m in out:
        outer = 1 if m['track'] == 'nwp' else -1
        m['side'] = outer if count[m['track']] % 2 == 0 else -outer
        count[m['track']] += 1
    return out


def _segment_hits_box(x0, y0, x1, y1, bb, pad):
    """ True if the segment (x0,y0)-(x1,y1) passes through bbox `bb` widened by `pad` in x.

    Liang-Barsky clipping against the rectangle.  Generated by JXP and Claude """
    xlo, xhi, ylo, yhi = bb.x0 - pad, bb.x1 + pad, min(bb.y0, bb.y1), max(bb.y0, bb.y1)
    dx, dy = x1 - x0, y1 - y0
    t0, t1 = 0.0, 1.0
    for p_, q_ in ((-dx, x0 - xlo), (dx, xhi - x0), (-dy, y0 - ylo), (dy, yhi - y0)):
        if p_ == 0:
            if q_ < 0:
                return False
            continue
        t = q_ / p_
        if p_ < 0:
            t0 = max(t0, t)
        else:
            t1 = min(t1, t)
        if t0 > t1:
            return False
    return True


def place_labels(ax, fig, items):
    """ Place labels above (NWP) or below (ocean) the track without overlaps.

    Labels alternate between the two sides of their track and are placed in date
    order.  Each is tried at increasing levels away from its
    track and, at each level, at a short list of anchorings (box ending at the marker,
    centred on it, starting at it, and small horizontal offsets of each); a slanted
    leader line joins marker and box.  A position is accepted when the box clears every
    box already placed, no leader already drawn crosses the new box, the new leader
    crosses no box already placed, and the box does not sit over the x of a marker on
    the same track whose label is still to be placed (so that later labels keep a free
    path); the last rule is dropped in a second pass only if nothing else fits.  The
    gap between the track and the first label level (FIRST_LEVEL) is what lets a leader
    step sideways.  Returns the highest level used.

    Generated by JXP and Claude """
    renderer = fig.canvas.get_renderer()
    placed = []                               # (bbox, leader segment) per placed label
    track_ys = [tr['y'] for tr in TRACKS.values()]
    xmin, xmax = ax.get_xlim()
    pad = 0.004 * (xmax - xmin)
    year = 365.25
    anchors = [('right', 0.0), ('right', 0.15), ('center', 0.0), ('center', -0.4), ('center', 0.4),
               ('left', 0.0), ('left', -0.15), ('right', 0.3), ('left', -0.3), ('right', 0.5),
               ('left', -0.5), ('center', -0.8), ('center', 0.8)]
    for n, it in enumerate(items):
        tr = TRACKS[it['track']]
        sign = it['side']
        x = mdates.date2num(it['x'])
        y_mark = tr['y'] + sign * 0.07
        va = 'bottom' if sign > 0 else 'top'
        later = [mdates.date2num(o['x']) for o in items[n + 1:]
                 if o['track'] == it['track'] and o['side'] == it['side']]
        txt, done = None, False
        for strict in (True, False):
            for lev in range(MAX_LEVELS):
                y = tr['y'] + sign * (FIRST_LEVEL + lev * LEVEL_STEP)
                for ha, dx in anchors:
                    xa = x + dx * year
                    if txt is not None:
                        txt.remove()
                    txt = ax.text(xa, y, it['label'], fontsize=FONT, ha=ha, va=va, color='#222222',
                                  linespacing=1.15, zorder=5)
                    bb = txt.get_window_extent(renderer).transformed(ax.transData.inverted())
                    if bb.x0 < xmin + pad or bb.x1 > xmax - pad:
                        continue          # outside the frame
                    if any(bb.y0 - 0.12 < ty < bb.y1 + 0.12 for ty in track_ys if ty != tr['y']):
                        continue          # would sit on the other track's line
                    if strict and any(bb.x0 - pad < lx < bb.x1 for lx in later):
                        continue          # would sit over a later marker on this track
                    y_edge = (bb.y0 if sign > 0 else bb.y1) - sign * 0.015
                    seg = (x, y_mark, xa, y_edge)
                    clash = False
                    for (obb, oseg) in placed:
                        if not (bb.x1 + pad < obb.x0 or bb.x0 - pad > obb.x1 or
                                bb.y1 < obb.y0 or bb.y0 > obb.y1):
                            clash = True  # boxes overlap
                        elif _segment_hits_box(*oseg, bb, pad):
                            clash = True  # an existing leader crosses the new box
                        elif _segment_hits_box(*seg, obb, pad):
                            clash = True  # the new leader crosses an existing box
                        if clash:
                            break
                    if not clash:
                        placed.append((bb, seg))
                        it['level'] = lev
                        done = True
                        break
                if done:
                    break
            if done:
                break
        if not done:
            for (obb, oseg) in placed:
                print(f"  placed: x {mdates.num2date(obb.x0).date()}..{mdates.num2date(obb.x1).date()} "
                      f"y {obb.y0:.2f}..{obb.y1:.2f}; leader x {mdates.num2date(oseg[0]).date()}"
                      f"->{mdates.num2date(oseg[2]).date()} y {oseg[1]:.2f}->{oseg[3]:.2f}")
            sys.exit(f"ERROR: could not place label for {it['key']} ({it['x']}) within {MAX_LEVELS} levels")
        ax.plot([seg[0], seg[2]], [seg[1], seg[3]], color='#9a9a9a', lw=0.6, zorder=2)
    ylo = min(min(bb.y0 for bb, _ in placed), min(track_ys))
    yhi = max(max(bb.y1 for bb, _ in placed), max(track_ys))
    return max(i['level'] for i in items), (ylo, yhi)


def main():
    """ Generated by JXP and Claude """
    items = load_milestones()
    n_nwp = sum(i['track'] == 'nwp' for i in items)
    print(f"{len(items)} milestones ({n_nwp} NWP, {len(items) - n_nwp} ocean); "
          f"bases: " + ', '.join(f"{b} {sum(i['basis'] == b for i in items)}" for b in ('arxiv', 'month', 'year')))

    fig, ax = plt.subplots(figsize=(13.0, 8.2), dpi=200, facecolor='white')
    ax.set_facecolor('white')
    ax.set_xlim(mdates.date2num(X0), mdates.date2num(X1))
    ax.set_ylim(TRACKS['ocean']['y'] - (FIRST_LEVEL + 4 * LEVEL_STEP) - 0.15,
                TRACKS['nwp']['y'] + (FIRST_LEVEL + 4 * LEVEL_STEP) + 0.15)

    # year grid and tracks
    for yr in range(2018, 2027):
        ax.axvline(mdates.date2num(dt.date(yr, 1, 1)), color='#e6e6e6', lw=0.7, zorder=0)
    for t, tr in TRACKS.items():
        ax.axhline(tr['y'], color=tr['color'], lw=1.6, alpha=0.55, zorder=1)
        ax.text(mdates.date2num(X0) - 0.012 * (mdates.date2num(X1) - mdates.date2num(X0)), tr['y'], tr['name'],
                ha='right', va='center', fontsize=10, fontweight='bold', color=tr['color'])

    # markers (with a year-span bar for year-only dates)
    for it in items:
        tr = TRACKS[it['track']]
        x = mdates.date2num(it['x'])
        if it['basis'] == 'year':
            ax.plot([mdates.date2num(dt.date(it['date'].year, 1, 1)),
                     mdates.date2num(dt.date(it['date'].year, 12, 31))],
                    [tr['y'], tr['y']], color=tr['color'], lw=5, alpha=0.18, solid_capstyle='butt', zorder=1)
        ax.plot(x, tr['y'], marker=CATEGORY_MARKERS[it['cat']], ms=7.0, mfc=tr['color'], mec='white',
                mew=0.9, ls='none', zorder=4)

    fig.canvas.draw()
    top, (ylo, yhi) = place_labels(ax, fig, items)
    print(f"labels placed on {top + 1} levels at most")
    # trim the empty space above and below the labels, keeping the same data units per
    # inch (so the placement just checked stays valid): shrink ylim and the figure height
    # together
    y0, y1 = ax.get_ylim()
    new_lo, new_hi = ylo - 0.15, yhi + 0.15
    ax.set_ylim(new_lo, new_hi)
    w, h = fig.get_size_inches()
    fig.set_size_inches(w, h * (new_hi - new_lo) / (y1 - y0) + 0.9)

    # axes cosmetics
    ax.xaxis.set_major_locator(mdates.YearLocator())
    ax.xaxis.set_major_formatter(mdates.DateFormatter('%Y'))
    ax.tick_params(axis='x', labelsize=9, length=3, colors='#444444')
    ax.set_yticks([])
    for side in ('left', 'right', 'top'):
        ax.spines[side].set_visible(False)
    ax.spines['bottom'].set_color('#888888')

    # legend: shape = category, colour = track, bar = year-only date
    handles = [Line2D([], [], marker=CATEGORY_MARKERS[c], ls='none', ms=7, mfc='#666666', mec='white',
                      label=CATEGORY_NAMES[c]) for c in (1, 2, 3, 4)]
    if any(i['basis'] == 'year' for i in items):
        handles.append(Line2D([], [], color='#666666', lw=5, alpha=0.25,
                              label='year-only date: plotted at mid-year, bar spans the year'))
    fig.legend(handles=handles, loc='lower center', fontsize=7.6, frameon=False, ncol=3,
               handletextpad=0.6, columnspacing=1.6, title='marker shape gives the taxonomy category; '
               'colour the track', title_fontsize=7.6, bbox_to_anchor=(0.5, 0.0))
    ax.set_title('AI in data assimilation, 2018-2026: exemplars cited in Sections 6 (NWP) and 7 (ocean)',
                 fontsize=10.5, loc='left', color='#222222', pad=8)

    fig.tight_layout(rect=(0, 0.10, 1, 1))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    fig.savefig(OUT, dpi=200, facecolor='white')
    print(f"wrote {OUT}")


if __name__ == '__main__':
    main()

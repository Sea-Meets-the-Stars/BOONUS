def cr_authors(cr, swap=False):
    """ Crossref author list as [(family, given)]; organizations as (name, '').

    swap=True exchanges the two fields, for records in which Crossref holds them
    reversed (lellouche2021copernicus: family='Jean-Michel', given='Lellouche').

    Generated by JXP and Claude
    """
    out = []
    for a in cr.get('author', []):
        if 'family' in a:
            fam, giv = a['family'].strip(), a.get('given', '').strip()
            if swap:
                fam, giv = giv, fam
            out.append((fam.replace('‐', '-'), giv.replace('‐', '-')))
        elif 'name' in a:
            out.append((a['name'].strip(), ''))
    return out


def arxiv_authors(names):
    """ arXiv 'Given Family' strings to [(family, given)]. Generated by JXP and Claude """
    out = []
    for n in names:
        parts = n.split()
        out.append((parts[-1], ' '.join(parts[:-1])) if len(parts) > 1 else (n, ''))
    return out


def initials(given):
    """ 'Andrew M.' -> 'A. M.'; 'Jean-Michel' -> 'J.-M.'. Generated by JXP and Claude """
    out = []
    for tok in given.replace('.', '. ').split():
        if not tok:
            continue
        out.append('-'.join(p[0] + '.' for p in tok.split('-') if p))
    return ' '.join(out)


def md_authors(auth):
    """ 'Family, I., Family, I., and Family, I.' for the Markdown file. Generated by JXP and Claude """
    names = [f'{f}, {initials(g)}' if g else f for f, g in auth]
    if len(names) == 1:
        return names[0]
    if len(names) == 2:
        return f'{names[0]} and {names[1]}'
    return ', '.join(names[:-1]) + ', and ' + names[-1]


def bib_authors(auth):
    """ 'Family, Given and Family, Given' for BibTeX. Generated by JXP and Claude """
    return ' and '.join(f'{f}, {g}' if g else '{' + f + '}' for f, g in auth)


def clean_title(t):
    """ Strip the HTML Crossref leaves in titles, collapse whitespace, normalize hyphens.

    Crossref titles can contain <scp>S</scp> outhern (small caps), CO <sub>2</sub> and
    <i>p</i> CO; these are rejoined into 'Southern', 'CO2' and 'pCO'.

    Generated by JXP and Claude
    """
    t = re.sub(r'<scp>\s*(.*?)\s*</scp>\s*', r'\1', t, flags=re.S)
    t = re.sub(r'\s*<sub>\s*(.*?)\s*</sub>', r'\1', t, flags=re.S)
    t = re.sub(r'\s*<sup>\s*(.*?)\s*</sup>', r'\1', t, flags=re.S)
    t = re.sub(r'<i>\s*(.*?)\s*</i>\s*', r'\1', t, flags=re.S)
    t = re.sub(r'<[^>]+>', '', t)
    return ' '.join(t.replace('‐', '-').replace('‑', '-').split())


def bib_escape(s):
    """ Escape the characters BibTeX treats specially in free text. Generated by JXP and Claude """
    return s.replace('&', r'\&').replace('%', r'\%').replace('_', r'\_').replace('#', r'\#')


def pages_field(cr):
    """ (pages, article_number) from a Crossref record. Generated by JXP and Claude """
    page = cr.get('page', '')
    art = cr.get('article-number', '')
    if page and '-' in page:
        a, b = page.split('-', 1)
        page = f'{a}--{b}'
    return page, art


def cr_year(cr):
    """ Year of first publication (Crossref 'issued'). Generated by JXP and Claude """
    for k in ('issued', 'published-online', 'published-print'):
        dp = cr.get(k, {}).get('date-parts', [[None]])[0]
        if dp and dp[0]:
            return str(dp[0])
    return ''


def status_of(e):
    """ verified | preprint | grey, per the reading-list convention. Generated by JXP and Claude """
    if 'grey' in e.get('flags', set()):
        return 'grey'
    if e['kind'] == 'arxiv':
        return 'preprint'
    return 'verified' if e.get('doi_code') and 300 <= e['doi_code'] < 400 else 'unverified'


def build_entry(e, use_cache):
    """ Attach the fetched metadata and verification results to an entry dict. Generated by JXP and Claude """
    e.setdefault('flags', set())
    if e['kind'] in ('article', 'incollection'):
        cr = crossref(e['doi'], use_cache)
        e['authors'] = cr_authors(cr, swap=e.get('swap_names', False))
        e['title'] = e.get('title_override') or clean_title(cr['title'][0])
        e['crossref_title'] = clean_title(cr['title'][0])
        e['journal'] = clean_title(cr.get('container-title', [''])[0]) if cr.get('container-title') else ''
        e['volume'] = cr.get('volume', '')
        e['issue'] = cr.get('issue', '')
        e['pages'], e['artnum'] = pages_field(cr)
        e['year'] = cr_year(cr)
        e['publisher'] = cr.get('publisher', '')
        e['doi_code'] = head_code('https://doi.org/' + e['doi'])
    if e['kind'] == 'arxiv':
        ax = arxiv(e['arxiv'], use_cache)
        e['authors'] = arxiv_authors(ax['authors'])
        e['title'] = ax['title']
        e['year'] = ax['year']
        e['primary'] = ax['primary']
        e['arxiv_updated'] = ax['updated']
        e['arxiv_doi'] = '10.48550/arXiv.' + e['arxiv']
        e['doi_code'] = head_code('https://doi.org/' + e['arxiv_doi'])
    elif e.get('arxiv'):
        # companion preprint of a journal article: confirm the ID points at the same paper
        ax = arxiv(e['arxiv'], use_cache)
        e['arxiv_title'] = ax['title']
        w_have = set(re.findall(r'[a-z0-9]{3,}', ax['title'].lower()))
        w_want = re.findall(r'[a-z0-9]{3,}', e['title'].lower())
        e['arxiv_match'] = sum(w in w_have for w in w_want) / max(1, len(w_want))
    if e['kind'] == 'grey':
        e['url_code'] = head_code_follow(e['url'])
        if e.get('url2'):
            e['url2_code'] = head_code_follow(e['url2'])
    return e



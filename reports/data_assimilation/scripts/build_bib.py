def cached_get(url, name, use_cache=True):
    """ GET a URL as text, caching the body under CACHE/name. Generated by JXP and Claude """
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, re.sub(r'[^A-Za-z0-9._-]', '_', name))
    if use_cache and os.path.exists(path):
        with open(path) as fh:
            return fh.read()
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as resp:
        body = resp.read().decode('utf-8')
    with open(path, 'w') as fh:
        fh.write(body)
    return body


def crossref(doi, use_cache=True):
    """ Crossref work record for a DOI (the 'message' object). Generated by JXP and Claude """
    body = cached_get('https://api.crossref.org/works/' + urllib.parse.quote(doi, safe=''),
                      'crossref_' + doi, use_cache)
    return json.loads(body)['message']


def arxiv(aid, use_cache=True):
    """ arXiv API record for an ID: dict(title, authors, year, month, primary, updated). Generated by JXP and Claude """
    body = cached_get('https://export.arxiv.org/api/query?id_list=' + aid, 'arxiv_' + aid, use_cache)
    ns = {'a': 'http://www.w3.org/2005/Atom', 'x': 'http://arxiv.org/schemas/atom'}
    entry = ET.fromstring(body).find('a:entry', ns)
    title = ' '.join(entry.find('a:title', ns).text.split())
    authors = [a.find('a:name', ns).text for a in entry.findall('a:author', ns)]
    published = entry.find('a:published', ns).text
    updated = entry.find('a:updated', ns).text
    prim = entry.find('x:primary_category', ns)
    return dict(title=title, authors=authors, year=published[:4], month=int(published[5:7]),
                primary=prim.get('term') if prim is not None else '', updated=updated[:10])


def head_code(url):
    """ HTTP status of `curl -sI url` (first response, no redirect following). Generated by JXP and Claude """
    res = subprocess.run(['curl', '-sI', '-A', UA['User-Agent'], '--max-time', '40', url],
                         capture_output=True, text=True)
    m = re.match(r'HTTP/[\d.]+\s+(\d{3})', res.stdout)
    return int(m.group(1)) if m else None


def head_code_follow(url):
    """ Final HTTP status of `curl -sI -L url`. Generated by JXP and Claude """
    res = subprocess.run(['curl', '-sI', '-L', '-A', UA['User-Agent'], '--max-time', '40', url],
                         capture_output=True, text=True)
    codes = re.findall(r'HTTP/[\d.]+\s+(\d{3})', res.stdout)
    return int(codes[-1]) if codes else None


